export const starterVocabulary = seeds.map(
  ([word, meaning, partOfSpeech, cefr, usageNote, distractors, sentences]) => ({
    ...wordInputSchema.parse({
      word,
      meanings: [meaning],
      partOfSpeech,
      cefr,
      usageNote,
      examples: sentences.map((sentence, index) => ({
        sentence,
        translation: starterTranslations[word]?.[index] ?? "",
        translationFocus: starterTranslationFocus[word]?.[index],
        source: "Atlas editoryal başlangıç seti",
      })),
      sourceUrl: `https://dictionary.cambridge.org/dictionary/english/${wordKey(word)}`,
    }),
    distractors,
  }),
);

export function getStarterWord(word: string) {
  return starterVocabulary.find((entry) => wordKey(entry.word) === wordKey(word));
}

export function enrichWordInput(input: WordInput): WordInput {
  const seed = getStarterWord(input.word);
  if (!seed) return input;
  return {
    ...seed,
    ...input,
    meanings: input.meanings?.length ? input.meanings : seed.meanings,
    examples: input.examples?.length ? input.examples : seed.examples,
    partOfSpeech: input.partOfSpeech || seed.partOfSpeech,
    usageNote: input.usageNote || seed.usageNote,
    cefr: input.cefr && input.cefr !== "Belirtilmedi" ? input.cefr : seed.cefr,
    sourceUrl: input.sourceUrl || seed.sourceUrl,
  };
}
